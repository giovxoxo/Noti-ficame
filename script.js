let currentGameKey = 'compra';
let currentWordSearch = null;
let foundWordsSet = new Set();
let selectedCells = [];
let gameTimer = null;
let gameSeconds = 0;
let isAudioPlaying = false;

function navigateTo(viewId) {
    document.querySelectorAll('.page-view').forEach(view => view.classList.remove('active'));
    document.getElementById(viewId).classList.add('active');
    window.scrollTo({ top: 0, behavior: 'smooth' });

    if (viewId === 'view-games') {
        loadWordSearch(currentGameKey);
    }
}

function openArticle(articleId) {
    const data = ARTICLES_DATA[articleId];
    if (!data) return;

    document.getElementById('art-tag').textContent = data.tag;
    document.getElementById('art-title').textContent = data.title;
    document.getElementById('art-subtitle').textContent = data.subtitle;
    document.getElementById('art-body').innerHTML = data.body;

    navigateTo('view-article');
}

