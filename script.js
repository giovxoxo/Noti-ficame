const audio = document.getElementById('myAudio');

function toggleAudio() {
    const btnIcon = document.getElementById('audioIcon');
    const timeDisplay = document.getElementById('audioTime');
    
    if (audio.paused) {
        audio.play();
        btnIcon.className = 'fa-solid fa-pause';
    } else {
        audio.pause();
        btnIcon.className = 'fa-solid fa-play';
    }
}

// Actualizar el tiempo de reproducción automáticamente en pantalla
if (audio) {
    audio.addEventListener('timeupdate', () => {
        const currentMins = String(Math.floor(audio.currentTime / 60)).padStart(2, '0');
        const currentSecs = String(Math.floor(audio.currentTime % 60)).padStart(2, '0');
        const totalMins = String(Math.floor(audio.duration / 60) || 0).padStart(2, '0');
        const totalSecs = String(Math.floor(audio.duration % 60) || 0).padStart(2, '0');
        
        document.getElementById('audioTime').textContent = `${currentMins}:${currentSecs} / ${totalMins}:${totalSecs}`;
    });
}

function loadWordSearch(gameKey) {
    currentGameKey = gameKey;
    currentWordSearch = WORDSEARCH_DATA[gameKey];
    foundWordsSet.clear();
    selectedCells = [];
    clearInterval(gameTimer);
    gameSeconds = 0;
    
    document.querySelectorAll('.game-select-btn').forEach(btn => btn.classList.remove('active'));
    event?.target?.classList.add('active');

    document.getElementById('ws-title').textContent = currentWordSearch.title;
    document.getElementById('found-count').textContent = '0';
    document.getElementById('total-count').textContent = currentWordSearch.words.length;
    document.getElementById('timer-display').textContent = 'Tiempo: 00:00';

    const listContainer = document.getElementById('word-list-items');
    listContainer.innerHTML = '';
    currentWordSearch.words.forEach(word => {
        const li = document.createElement('li');
        li.id = `word-${word}`;
        li.textContent = word;
        listContainer.appendChild(li);
    });

    const gridContainer = document.getElementById('wordsearch-grid');
    const cols = currentWordSearch.grid[0].length;
    gridContainer.style.gridTemplateColumns = `repeat(${cols}, 1fr)`;
    gridContainer.innerHTML = '';

    currentWordSearch.grid.forEach((row, r) => {
        row.forEach((char, c) => {
            const cell = document.createElement('div');
            cell.className = 'ws-cell';
            cell.textContent = char;
            cell.dataset.row = r;
            cell.dataset.col = c;

            cell.addEventListener('click', () => handleCellClick(cell, r, c, char));
            gridContainer.appendChild(cell);
        });
    });

    gameTimer = setInterval(() => {
        gameSeconds++;
        const mins = String(Math.floor(gameSeconds / 60)).padStart(2, '0');
        const secs = String(gameSeconds % 60).padStart(2, '0');
        document.getElementById('timer-display').textContent = `Tiempo: ${mins}:${secs}`;
    }, 1000);
}

function handleCellClick(cell, r, c, char) {
    if (cell.classList.contains('found')) return;

    const index = selectedCells.findIndex(item => item.r === r && item.c === c);
    if (index >= 0) {
        selectedCells.splice(index, 1);
        cell.classList.remove('selected');
    } else {
        selectedCells.push({ r, c, char, el: cell });
        cell.classList.add('selected');
    }

    checkSelectedWord();
}

function checkSelectedWord() {
    const selectedString = selectedCells.map(item => item.char).join('');
    const reversedString = selectedString.split('').reverse().join('');

    const matchedWord = currentWordSearch.words.find(w => w === selectedString || w === reversedString);

    if (matchedWord && !foundWordsSet.has(matchedWord)) {
        foundWordsSet.add(matchedWord);
        
        selectedCells.forEach(item => {
            item.el.classList.remove('selected');
            item.el.classList.add('found');
        });
        
        document.getElementById(`word-${matchedWord}`)?.classList.add('found');
        document.getElementById('found-count').textContent = foundWordsSet.size;

        selectedCells = [];

        if (foundWordsSet.size === currentWordSearch.words.length) {
            clearInterval(gameTimer);
            setTimeout(() => {
                alert(`¡Felicitaciones! Completaste la sopa de letras en ${document.getElementById('timer-display').textContent}`);
            }, 300);
        }
    }
}